@app.post("/api/rooms")
def create_room():
    data = read_payload()
    username = str(data.get("username", "")).strip()
    room_name = str(data.get("room_name", "")).strip()
    if not username or len(username) > 24:
        return json_error("Enter a name between 1 and 24 characters.")
    if len(room_name) > 50:
        return json_error("Room names must be 50 characters or fewer.")
    if not room_name:
        room_name = f"{username}'s auction"

    member_id = secrets.token_urlsafe(18)
    with db_connection() as connection:
        begin_write(connection)
        player = connection.execute(
            "SELECT id FROM players ORDER BY RANDOM() LIMIT 1"
        ).fetchone()
        if player is None:
            return json_error("There are no players available to auction.", 503)
        code = new_room_code(connection)
        connection.execute(
            """
            INSERT INTO rooms (code, name, owner_id, current_player_id)
            VALUES (?, ?, ?, ?)
            """,
            (code, room_name, member_id, player["id"]),
        )
        connection.execute(
            """
            INSERT INTO room_members (id, room_code, name, budget)
            VALUES (?, ?, ?, ?)
            """,
            (member_id, code, username, STARTING_BUDGET),
        )
        connection.execute(
            """
            INSERT INTO room_auction_players
            (room_code, player_id, status, created_at)
            VALUES (?, ?, 'live', CURRENT_TIMESTAMP)
            """,
            (code, player["id"]),
        )
    return jsonify({"code": code, "member_id": member_id})


@app.post("/api/rooms/<code>/join")
def join_room(code):
    data = read_payload()
    username = str(data.get("username", "")).strip()
    member_id = str(data.get("member_id", "")).strip() or secrets.token_urlsafe(18)
    if not username or len(username) > 24:
        return json_error("Enter a name between 1 and 24 characters.")

    with db_connection() as connection:
        begin_write(connection)
        room = connection.execute(
            lock_room_query("SELECT code FROM rooms WHERE code = ?"),
            (code.upper(),),
        ).fetchone()
        if room is None:
            return json_error("This room does not exist.", 404)
        member = connection.execute(
            "SELECT id FROM room_members WHERE id = ? AND room_code = ?",
            (member_id, room["code"]),
        ).fetchone()
        if member is None:
            member_id = secrets.token_urlsafe(18)
            connection.execute(
                """
                INSERT INTO room_members (id, room_code, name, budget)
                VALUES (?, ?, ?, ?)
                """,
                (member_id, room["code"], username, STARTING_BUDGET),
            )
    return jsonify({"member_id": member_id})


@app.get("/api/rooms/<code>")
def room_state(code):
    member_id = request.args.get("member_id", "")
    with db_connection() as connection:
        room = connection.execute(
            "SELECT * FROM rooms WHERE code = ?", (code.upper(),)
        ).fetchone()
        if room is None:
            return json_error("This room does not exist.", 404)
        member = connection.execute(
            """
            SELECT id, name, budget FROM room_members
            WHERE id = ? AND room_code = ?
            """,
            (member_id, room["code"]),
        ).fetchone()
        if member is None:
            return jsonify(
                {
                    "joined": False,
                    "room": {
                        "code": room["code"],
                        "name": room["name"],
                        "invite_url": room_invite_url(room["code"]),
                    },
                }
            )

        current_player = None
        if room["current_player_id"] is not None:
            current_player = connection.execute(
                """
                SELECT p.id, p.player_name, p.club, p.position, p.nationality,
                       p.tier, p.market_value_eur_m, p.age, p.sub_position,
                       a.bid, a.bidder_id, m.name AS bidder_name
                FROM players p
                JOIN room_auction_players a
                  ON a.player_id = p.id AND a.room_code = ?
                LEFT JOIN room_members m ON m.id = a.bidder_id
                WHERE p.id = ?
                """,
                (room["code"], room["current_player_id"]),
            ).fetchone()
        members = connection.execute(
            """
            SELECT m.id, m.name, m.budget, COUNT(a.player_id) AS players_won
            FROM room_members m
            LEFT JOIN room_auction_players a
              ON a.bidder_id = m.id AND a.status = 'sold'
            WHERE m.room_code = ?
            GROUP BY m.id
            ORDER BY m.created_at, m.name
            """,
            (room["code"],),
        ).fetchall()
        history = connection.execute(
            """
            SELECT p.player_name, p.club, a.status, a.bid, m.name AS winner_name
            FROM room_auction_players a
            JOIN players p ON p.id = a.player_id
            LEFT JOIN room_members m ON m.id = a.bidder_id
            WHERE a.room_code = ? AND a.status != 'live'
            ORDER BY a.created_at DESC
            LIMIT 8
            """,
            (room["code"],),
        ).fetchall()

    player_data = dict(current_player) if current_player else None
    if player_data is not None:
        player_data["next_bid"] = (
            player_data["bid"]
            if player_data["bid"] > 0
            else player_data["market_value_eur_m"]
        )
        if player_data["bid"] > 0:
            player_data["next_bid"] += BID_INCREMENT

    return jsonify(
        {
            "joined": True,
            "room": {
                "code": room["code"],
                "name": room["name"],
                "status": room["status"],
                "invite_url": room_invite_url(room["code"]),
            },
            "member": dict(member),
            "is_owner": member["id"] == room["owner_id"],
            "current_player": player_data,
            "members": [
                {**dict(row), "is_owner": row["id"] == room["owner_id"]}
                for row in members
            ],
            "history": [dict(row) for row in reversed(history)],
            "bid_increment": BID_INCREMENT,
        }
    )


@app.post("/api/rooms/<code>/bid")
def place_bid(code):
    member_id = str(read_payload().get("member_id", "")).strip()
    if not member_id:
        return json_error("Join the room before bidding.", 401)

    with db_connection() as connection:
        begin_write(connection)
        room = connection.execute(
            lock_room_query("SELECT * FROM rooms WHERE code = ?"),
            (code.upper(),),
        ).fetchone()
        if room is None:
            return json_error("This room does not exist.", 404)
        member = connection.execute(
            """
            SELECT id, budget FROM room_members
            WHERE id = ? AND room_code = ?
            """,
            (member_id, room["code"]),
        ).fetchone()
        if member is None:
            return json_error("Join the room before bidding.", 401)
        if room["status"] != "live" or room["current_player_id"] is None:
            return json_error("There is no active player to bid on.", 409)
        auction = connection.execute(
            """
            SELECT a.bid, a.bidder_id, p.market_value_eur_m
            FROM room_auction_players a
            JOIN players p ON p.id = a.player_id
            WHERE a.room_code = ? AND a.player_id = ? AND a.status = 'live'
            """,
            (room["code"], room["current_player_id"]),
        ).fetchone()
        if auction is None:
            return json_error("The current auction is not available.", 409)
        if auction["bidder_id"] == member_id:
            return json_error("You already hold the highest bid.", 409)
        next_bid = (
            auction["market_value_eur_m"]
            if auction["bid"] == 0
            else auction["bid"] + BID_INCREMENT
        )
        if member["budget"] < next_bid:
            return json_error("Your remaining budget is too low for this bid.", 409)
        connection.execute(
            """
            UPDATE room_auction_players
            SET bid = ?, bidder_id = ?
            WHERE room_code = ? AND player_id = ?
            """,
            (next_bid, member_id, room["code"], room["current_player_id"]),
        )
    return jsonify({"bid": next_bid})


@app.post("/api/rooms/<code>/next")
def advance_auction(code):
    member_id = str(read_payload().get("member_id", "")).strip()
    with db_connection() as connection:
        begin_write(connection)
        room = connection.execute(
            lock_room_query("SELECT * FROM rooms WHERE code = ?"),
            (code.upper(),),
        ).fetchone()
        if room is None:
            return json_error("This room does not exist.", 404)
        if not member_id or member_id != room["owner_id"]:
            return json_error("Only the room creator can advance the auction.", 403)
        if room["status"] != "live" or room["current_player_id"] is None:
            return json_error("There is no active player to close.", 409)

        auction = connection.execute(
            """
            SELECT bid, bidder_id FROM room_auction_players
            WHERE room_code = ? AND player_id = ? AND status = 'live'
            """,
            (room["code"], room["current_player_id"]),
        ).fetchone()
        if auction is None:
            return json_error("The current auction is not available.", 409)
        if auction["bidder_id"] is not None:
            connection.execute(
                """
                UPDATE room_auction_players
                SET status = 'sold'
                WHERE room_code = ? AND player_id = ?
                """,
                (room["code"], room["current_player_id"]),
            )
            connection.execute(
                "UPDATE room_members SET budget = budget - ? WHERE id = ?",
                (auction["bid"], auction["bidder_id"]),
            )
        else:
            connection.execute(
                """
                UPDATE room_auction_players
                SET status = 'unsold'
                WHERE room_code = ? AND player_id = ?
                """,
                (room["code"], room["current_player_id"]),
            )

        next_player = connection.execute(
            """
            SELECT id FROM players
            WHERE id NOT IN (
                SELECT player_id FROM room_auction_players WHERE room_code = ?
            )
            ORDER BY RANDOM()
            LIMIT 1
            """,
            (room["code"],),
        ).fetchone()
        if next_player is None:
            connection.execute(
                "UPDATE rooms SET current_player_id = NULL, status = 'complete' WHERE code = ?",
                (room["code"],),
            )
        else:
            connection.execute(
                """
                INSERT INTO room_auction_players
                (room_code, player_id, status, created_at)
                VALUES (?, ?, 'live', CURRENT_TIMESTAMP)
                """,
                (room["code"], next_player["id"]),
            )
            connection.execute(
                "UPDATE rooms SET current_player_id = ? WHERE code = ?",
                (next_player["id"], room["code"]),
            )
    return jsonify({"ok": True})


