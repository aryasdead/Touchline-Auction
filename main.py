def connect_db():
    if USE_POSTGRES:
        import psycopg
        from psycopg.rows import dict_row

        return psycopg.connect(
            DATABASE_URL, row_factory=dict_row, connect_timeout=10
        )
    connection = sqlite3.connect(DATABASE, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


class DatabaseConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, parameters=()):
        if USE_POSTGRES:
            query = query.replace("?", "%s")
        return self.connection.execute(query, parameters)

    def executemany(self, query, parameters):
        if USE_POSTGRES:
            query = query.replace("?", "%s")
        return self.connection.cursor().executemany(query, parameters)


@contextmanager
def db_connection():
    connection = connect_db()
    try:
        with connection:
            yield DatabaseConnection(connection)
    finally:
        connection.close()


def initialize_db():
    with db_connection() as connection:
        if USE_POSTGRES:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS players (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    player_name TEXT,
                    club TEXT,
                    position TEXT,
                    nationality TEXT,
                    tier TEXT,
                    market_value_eur_m REAL,
                    age INTEGER,
                    sub_position TEXT,
                    height_ft TEXT,
                    UNIQUE(club, nationality, player_name)
                )
                """
            )
        else:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS players (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    player_name TEXT,
                    club TEXT,
                    position TEXT,
                    nationality TEXT,
                    tier REAL,
                    market_value_eur_m REAL,
                    age INTEGER,
                    sub_position TEXT,
                    height_ft TEXT,
                    UNIQUE(club, nationality, player_name)
                )
                """
            )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS rooms (
                code TEXT PRIMARY KEY,
                name TEXT NOT NULL,
                owner_id TEXT NOT NULL,
                current_player_id INTEGER,
                status TEXT NOT NULL DEFAULT 'live',
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
        )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS room_members (
                id TEXT PRIMARY KEY,
                room_code TEXT NOT NULL REFERENCES rooms(code) ON DELETE CASCADE,
                name TEXT NOT NULL,
                budget INTEGER NOT NULL DEFAULT 700,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """
        )
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS room_auction_players (
                room_code TEXT NOT NULL REFERENCES rooms(code) ON DELETE CASCADE,
                player_id INTEGER NOT NULL REFERENCES players(id),
                status TEXT NOT NULL,
                bid INTEGER NOT NULL DEFAULT 0,
                bidder_id TEXT,
                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                PRIMARY KEY (room_code, player_id)
            )
            """
        )
        if USE_POSTGRES:
            connection.execute(
                """
                ALTER TABLE room_auction_players
                ADD COLUMN IF NOT EXISTS created_at TIMESTAMP NOT NULL
                DEFAULT CURRENT_TIMESTAMP
                """
            )
        else:
            columns = {
                row["name"]
                for row in connection.execute(
                    "PRAGMA table_info(room_auction_players)"
                ).fetchall()
            }
            if "created_at" not in columns:
                connection.execute(
                    "ALTER TABLE room_auction_players ADD COLUMN created_at TEXT"
                )
                connection.execute(
                    """
                    UPDATE room_auction_players SET created_at = CURRENT_TIMESTAMP
                    WHERE created_at IS NULL
                    """
                )
        player_count = connection.execute(
            "SELECT COUNT(*) AS player_count FROM players"
        ).fetchone()["player_count"]
        if player_count == 0 and PLAYER_CSV.exists():
            with PLAYER_CSV.open(newline="", encoding="utf-8") as player_file:
                reader = csv.DictReader(player_file)
                connection.executemany(
                    """
                    INSERT INTO players
                    (player_name, club, position, nationality, tier,
                     market_value_eur_m, age, sub_position, height_ft)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
                    ON CONFLICT (club, nationality, player_name) DO NOTHING
                    """,
                    (
                        (
                            row["player_name"],
                            row["club"],
                            row["position"],
                            row["nationality"],
                            row["tier"],
                            row["market_value_eur_m"],
                            row["age"],
                            row["sub_position"],
                            row["height_ft"],
                        )
                        for row in reader
                    ),
                )


def new_room_code(connection):
    while True:
        code = "".join(
            secrets.choice(ROOM_CODE_CHARACTERS) for _ in range(6)
        )
        if connection.execute(
            "SELECT 1 FROM rooms WHERE code = ?", (code,)
        ).fetchone() is None:
            return code


def json_error(message, status=400):
    return jsonify({"error": message}), status


def read_payload():
    return request.get_json(silent=True) or {}


def begin_write(connection):
    if not USE_POSTGRES:
        connection.execute("BEGIN IMMEDIATE")


def lock_room_query(query):
    return query + (" FOR UPDATE" if USE_POSTGRES else "")


def room_invite_url(code):
    parts = urlsplit(request.host_url)
    if parts.hostname in {"localhost", "127.0.0.1", "0.0.0.0"}:
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as route:
            try:
                route.connect(("192.0.2.1", 80))
            except OSError:
                pass
            else:
                lan_ip = route.getsockname()[0]
                if ipaddress.ip_address(lan_ip).is_private:
                    port = f":{parts.port}" if parts.port else ""
                    parts = parts._replace(netloc=f"{lan_ip}{port}")
    return urlunsplit(
        (parts.scheme, parts.netloc, f"/room/{code}", "", "")
    )


